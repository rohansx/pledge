-- Grant pledge_probe SELECT on commitment.resolved_at.
--
-- WHY THIS WAS MISSING, AND WHY IT DID NOT SHOW UP LOCALLY
--
-- Migration 0000 grants the probe role UPDATE on (status, resolved_at) but SELECT on only
-- (id, done_spec_hash, deadline, status, committed_at) — resolved_at is absent from the
-- SELECT list. That looks harmless: the worker writes resolved_at, it does not read it.
--
-- But resolveFromProbe ends in `RETURNING status, resolved_at`, and in Postgres a RETURNING
-- clause is a read. Without SELECT on the column the whole statement is refused with
-- "permission denied for table commitment" (42501) — a table-level message for a
-- column-level omission, which is what made it hard to see.
--
-- Every developer database had the grant, because it was added by hand while debugging and
-- never written down. So the suite was green on every machine and red the first time CI ran
-- against a database built purely from these migrations. The tests were fine; the migrations
-- were incomplete. This is exactly the drift that "role grants live in the first migration"
-- (CLAUDE.md, Conventions) exists to prevent, and it is worth noting the convention did not
-- save us — only a from-scratch build did.
--
-- Forward-only, per the same conventions: this adds a grant, it never narrows one.
GRANT SELECT (resolved_at) ON commitment TO pledge_probe;
